
import assert from "node:assert/strict";
import { describe, it } from "node:test";
import { network } from "hardhat";
import { decodeEventLog } from "viem";

describe("ConsentRegistry", async function () {
  const { viem } = await network.create();
  const publicClient = await viem.getPublicClient();

  async function createConsent(
    registry: Awaited<ReturnType<typeof viem.deployContract<"ConsentRegistry">>>,
    artefactHash: `0x${string}`,
    nonce: bigint,
  ): Promise<`0x${string}`> {
    const expiry = BigInt(Math.floor(Date.now() / 1000) + 3600);

    // The updated contract takes three arguments.
    const txHash = await registry.write.createConsent([
      artefactHash,
      expiry,
      nonce,
    ]);

    const receipt = await publicClient.waitForTransactionReceipt({
      hash: txHash,
    });

    // Read the ID generated by the smart contract.
    for (const log of receipt.logs) {
      try {
        const event = decodeEventLog({
          abi: registry.abi,
          data: log.data,
          topics: log.topics,
        });

        if (event.eventName === "ConsentCreated") {
          const args = event.args as { consentId: `0x${string}` };
          return args.consentId;
        }
      } catch {
        // Ignore unrelated event logs.
      }
    }

    throw new Error("ConsentCreated event not found");
  }

  it("creates and grants consent, then accepts the correct hash", async function () {
    const registry = await viem.deployContract("ConsentRegistry");
    const artefactHash = `0x${"22".repeat(32)}` as `0x${string}`;

    const consentId = await createConsent(registry, artefactHash, 1n);

    await registry.write.grantConsent([consentId]);

    const valid = await registry.read.isValid([
      consentId,
      artefactHash,
    ]);

    assert.equal(valid, true);
  });

  it("rejects a tampered document hash", async function () {
    const registry = await viem.deployContract("ConsentRegistry");
    const artefactHash = `0x${"44".repeat(32)}` as `0x${string}`;
    const tamperedHash = `0x${"55".repeat(32)}` as `0x${string}`;

    const consentId = await createConsent(registry, artefactHash, 2n);

    await registry.write.grantConsent([consentId]);

    const valid = await registry.read.isValid([
      consentId,
      tamperedHash,
    ]);

    assert.equal(valid, false);
  });

  it("rejects consent after it has been revoked", async function () {
    const registry = await viem.deployContract("ConsentRegistry");
    const artefactHash = `0x${"77".repeat(32)}` as `0x${string}`;

    const consentId = await createConsent(registry, artefactHash, 3n);

    await registry.write.grantConsent([consentId]);
    await registry.write.revokeConsent([consentId]);

    const valid = await registry.read.isValid([
      consentId,
      artefactHash,
    ]);

    assert.equal(valid, false);
  });
});
